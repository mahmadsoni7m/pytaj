package tj.pythontaj.content

import tj.pythontaj.domain.ErrorHelp

/** Ёрии маҳаллии (бе интернет) барои хатоҳои маъмул. Матнҳоро ба осонӣ таҳрир кунед. */
object ErrorHelper {
    fun explain(errorType: String?): ErrorHelp? {
        if (errorType == null) return null
        return when (errorType) {
            "SyntaxError" -> ErrorHelp(
                "SyntaxError — хатои синтаксис",
                "Python кодро хонда натавонист, чунки қоидаҳои навишт вайрон шудаанд.",
                listOf("Қавс ё нохунак баста нашудааст", "Дар охири сатри if/for/while/def нишони «:» нест", "Калимаи калидӣ нодуруст навишта шудааст (масалан prnt)"),
                "print(\"Салом\"", "print(\"Салом\")",
            )
            "IndentationError" -> ErrorHelp(
                "IndentationError — хатои ақибнишинӣ",
                "Фосилаҳои аввали сатр нодурустанд. Python ба ақибнишинӣ эътибор медиҳад.",
                listOf("Баъд аз «:» сатри навбатӣ ақибнишинӣ надорад", "Дар як блок шумораи фосилаҳо гуногун аст", "Табулятсия ва фосила омехта шудаанд"),
                "if 5 > 3:\nprint(\"ҳа\")", "if 5 > 3:\n    print(\"ҳа\")",
            )
            "NameError" -> ErrorHelp(
                "NameError — ном таъриф нашудааст",
                "Python номеро, ки шумо истифода кардед, намешиносад.",
                listOf("Тағйирёбанда пеш аз истифода сохта нашудааст", "Хатои имло ё ҳарфи калон/хурд (ном ва Ном гуногунанд)", "Матн бе нохунак навишта шудааст"),
                "print(салом)", "салом = \"Салом\"\nprint(салом)",
            )
            "TypeError" -> ErrorHelp(
                "TypeError — навъи нодуруст",
                "Амал байни навъҳои номувофиқ анҷом дода шуд ё ба функсия аргументи нодуруст дода шуд.",
                listOf("Ҷамъ кардани матн ва рақам", "Шумораи аргументҳо нодуруст аст", "Чизеро даъват кардаед, ки функсия нест"),
                "print(\"Синну сол: \" + 20)", "print(\"Синну сол: \" + str(20))",
            )
            "ValueError" -> ErrorHelp(
                "ValueError — арзиши нодуруст",
                "Навъи арзиш дуруст аст, вале мазмунаш барои ин амал мувофиқ нест.",
                listOf("Матни ғайрирақамиро ба int() додаед", "Дар input() рақам ворид нашудааст"),
                "int(\"abc\")", "int(\"123\")",
            )
            "IndexError" -> ErrorHelp(
                "IndexError — индекс аз ҳудуд берун аст",
                "Шумо элементеро мепурсед, ки дар рӯйхат вуҷуд надорад.",
                listOf("Индекс аз 0 оғоз мешавад: рӯйхати 3 элементӣ индексҳои 0,1,2 дорад", "Рӯйхат холӣ аст"),
                "a = [1, 2, 3]\nprint(a[3])", "a = [1, 2, 3]\nprint(a[2])",
            )
            "KeyError" -> ErrorHelp(
                "KeyError — калид ёфт нашуд",
                "Дар луғат чунин калид нест.",
                listOf("Хатои имло дар калид", "Калид ҳанӯз илова нашудааст"),
                "d = {\"ном\": \"Алӣ\"}\nprint(d[\"син\"])", "d = {\"ном\": \"Алӣ\"}\nprint(d.get(\"син\", \"номаълум\"))",
            )
            "ZeroDivisionError" -> ErrorHelp(
                "ZeroDivisionError — тақсим ба сифр",
                "Тақсим ба сифр дар риёзиёт номумкин аст.",
                listOf("Тақсимкунанда сифр аст", "Тағйирёбанда ногаҳон ба 0 баробар шудааст"),
                "print(10 / 0)", "b = 2\nif b != 0:\n    print(10 / b)",
            )
            "AttributeError" -> ErrorHelp(
                "AttributeError — хосият ё метод нест",
                "Ин объект чунин хосият ё методро надорад.",
                listOf("Метод барои ин навъ вуҷуд надорад (масалан append барои int)", "Хатои имло дар номи метод"),
                "x = 5\nx.append(1)", "x = [5]\nx.append(1)",
            )
            "ImportError", "ModuleNotFoundError" -> ErrorHelp(
                "ImportError — модул ёфт нашуд",
                "Python модули дархостшударо ёфта натавонист ё иҷозат нест.",
                listOf("Хатои имло дар номи модул", "Китобхонаи берунӣ дар ин барнома насб нашудааст (pip дастгирӣ намешавад)", "Модул барои амният манъ шудааст (масалан socket)"),
                "import mth", "import math",
            )
            else -> ErrorHelp(
                "$errorType — хато",
                "Хато дар сатри нишондодашуда рух додааст. Паёми хаторо бодиққат хонед: он сабабро мегӯяд.",
                listOf("Сатри хатоиро аз нав санҷед", "Арзиши тағйирёбандаҳоро бо print() бубинед"),
                "", "",
            )
        }
    }
}
